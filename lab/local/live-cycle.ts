import { randomUUID } from 'node:crypto';
import * as v from 'valibot';
import type { GithubReadConfig } from '../../src/github/fetch-issue';
import { sanitizeFailureMessage } from '../../src/tracer/redactor';
import type { BrowserMode } from '../../src/types/fix-run-result';
import type { UsageRatesTable } from '../../src/types/usage-summary';
import {
    captureGithubIssueRevision,
    type CaptureGithubIssueRevisionOptions,
    type GithubIssueExporterDependencies,
    type LiveIssueCaptureResult,
} from './github-issue-exporter';
import {
    LocalCycleResultSchema,
    executeVerifiedLocalCycle,
    writeLocalCycleResult,
    type LocalCycleDependencies,
    type LocalCycleResult,
} from './local-cycle';
import { clearLocalRunOutputDir } from '../../src/local/output-directory';

/**
 * Runtime controls of one targeted live issue cycle.
 */
export interface LiveCycleRuntimeOptions {
    /**
     * Browser-first execution policy.
     */
    browserMode: BrowserMode;

    /**
     * Whether temporary extension preparation should be retained.
     */
    keepTemporaryFiles: boolean;

    /**
     * Optional reasoning model override.
     */
    model?: string;

    /**
     * Whether verbose operational logging is enabled.
     */
    verbose: boolean;

    /**
     * Frozen per-model rates the fix runner prices its LLM usage from; when absent every cost is
     * reported as unknown.
     */
    pricingSnapshot?: UsageRatesTable;

    /**
     * Optional merged command interruption signal.
     */
    signal?: AbortSignal;

    /**
     * Validated executor set this run locks, already checked against the registered names; absent
     * locks the lab's own declared set.
     */
    executors?: readonly string[];

    /**
     * The repository's own lint command line, run over each candidate in the local filters source
     * (the clone when there is none); absent runs no lint.
     */
    lintCommand?: string;

    /**
     * Opaque CLI-license redactor retained by the executable command scope.
     */
}

/**
 * Options for one explicitly targeted read-only live issue cycle.
 */
export interface TargetedLiveIssueCycleOptions extends LiveCycleRuntimeOptions {
    /**
     * Read-only GitHub repository credentials.
     */
    github: GithubReadConfig;

    /**
     * Positive target issue number.
     */
    issueNumber: number;

    /**
     * Dedicated cycle output directory.
     */
    outputDir: string;
}

/**
 * Injectable live-cycle seams, none of which grant GitHub mutation authority.
 */
export interface LiveCycleDependencies extends LocalCycleDependencies {
    /**
     * Optional live capture seam used by deterministic tests.
     */
    captureIssueRevision?: (
        config: GithubReadConfig,
        issueNumber: number,
        options?: CaptureGithubIssueRevisionOptions,
        dependencies?: GithubIssueExporterDependencies,
    ) => Promise<LiveIssueCaptureResult>;
}

/**
 * Normalize and validate one cycle UUID generated by an injectable source.
 *
 * @param value - Candidate UUID.
 * @returns Validated UUID.
 */
function cycleId(value: string): string {
    return v.parse(v.pipe(v.string(), v.uuid()), value);
}

/**
 * Terminal status of one pre-handler cycle result, produced without model or browser work.
 */
const PreHandlerCycleStatus = {
    /**
     * The live issue's revision could not be captured.
     */
    LiveIntakeFailed: 'live_intake_failed',

    /**
     * The selected live issue revision was invalid, superseded, or the issue closed first.
     */
    InvalidLiveRevision: 'invalid_live_revision',
} as const;

/**
 * PreHandlerCycleStatus value.
 */
type PreHandlerCycleStatus = (typeof PreHandlerCycleStatus)[keyof typeof PreHandlerCycleStatus];

/**
 * Create a validated pre-handler result without model or browser work.
 *
 * @param base - Cycle identity, timestamps, and selector provenance.
 * @param status - Terminal pre-handler status.
 * @param completedAt - Fixed completion timestamp.
 * @param failure - Optional typed bounded failure.
 * @returns Validated result with no revision or investigation path.
 */
function preHandlerResult(
    base: Pick<LocalCycleResult, 'schemaVersion' | 'cycleId' | 'startedAt' | 'selection'>,
    status: PreHandlerCycleStatus,
    completedAt: string,
    failure: LocalCycleResult['failure'],
): LocalCycleResult {
    return v.parse(LocalCycleResultSchema, {
        ...base,
        completedAt,
        status,
        revision: null,
        investigationResultPath: null,
        outcome: null,
        failure,
    });
}

/**
 * Fail compilation when a capture result variant is not handled.
 *
 * @param value - Statically impossible value.
 * @returns Never.
 */
function assertNever(value: never): never {
    throw new Error(`Unhandled live capture result: ${JSON.stringify(value)}`);
}

/**
 * Convert live capture rejection into one typed pre-handler result.
 *
 * @param capture - Non-verified exhaustive capture branch.
 * @param base - Cycle identity and selection.
 * @param completedAt - Fixed completion timestamp.
 * @param token - Exact GitHub token used for sanitization.
 * @returns Typed local cycle result.
 */
function captureFailureResult(
    capture: Exclude<
        LiveIssueCaptureResult,
        {
            /**
             * Verified branch discriminator excluded from failure handling.
             */
            kind: 'verified';
        }
    >,
    base: Pick<LocalCycleResult, 'schemaVersion' | 'cycleId' | 'startedAt' | 'selection'>,
    completedAt: string,
    token: string,
): LocalCycleResult {
    switch (capture.kind) {
        case 'invalid':
            return preHandlerResult(base, PreHandlerCycleStatus.InvalidLiveRevision, completedAt, {
                code: 'invalid_live_revision',
                message: sanitizeFailureMessage(capture.message, [token]),
            });
        case 'superseded':
            return preHandlerResult(base, PreHandlerCycleStatus.LiveIntakeFailed, completedAt, {
                code: 'live_intake_failed',
                message: 'The live issue changed while its selected revision was being captured.',
            });
        case 'closed':
            return preHandlerResult(base, PreHandlerCycleStatus.LiveIntakeFailed, completedAt, {
                code: 'live_intake_failed',
                message: 'The live issue closed before its selected revision was captured.',
            });
        default:
            return assertNever(capture);
    }
}

/**
 * Run one explicitly targeted live issue through the common verified handler.
 *
 * @param options - Read-only issue selector, output path, and runtime controls.
 * @param dependencies - Injectable capture, provider, handler, clock, and identity seams.
 * @returns Persisted typed terminal cycle result.
 */
export async function runTargetedLiveIssueCycle(
    options: TargetedLiveIssueCycleOptions,
    dependencies: LiveCycleDependencies = {},
): Promise<LocalCycleResult> {
    const outputDir = clearLocalRunOutputDir(options.outputDir, process.cwd());
    const createCycleId = dependencies.createCycleId ?? randomUUID;
    const now = dependencies.now ?? (() => new Date().toISOString());
    const id = cycleId(createCycleId());
    const startedAt = now();
    const base = {
        schemaVersion: 1 as const,
        cycleId: id,
        startedAt,
        selection: { kind: 'live_issue' as const, issueNumber: options.issueNumber },
    };
    const capture = dependencies.captureIssueRevision ?? captureGithubIssueRevision;
    let captured: LiveIssueCaptureResult;
    try {
        captured = await capture(options.github, options.issueNumber, { capturedAt: startedAt });
    } catch (error) {
        return writeLocalCycleResult(
            outputDir,
            preHandlerResult(base, PreHandlerCycleStatus.LiveIntakeFailed, now(), {
                code: 'live_intake_failed',
                message: sanitizeFailureMessage(error, [options.github.token]),
            }),
        );
    }
    if (captured.kind !== 'verified') {
        return writeLocalCycleResult(
            outputDir,
            captureFailureResult(captured, base, now(), options.github.token),
        );
    }
    const result = await executeVerifiedLocalCycle(
        {
            revision: captured.revision,
            selection: base.selection,
            outputDir,
            cycleId: id,
            startedAt,
            handlerOptions: {
                environment: 'current',
                keepTemporaryFiles: options.keepTemporaryFiles,
                browserMode: options.browserMode,
                model: options.model,
                verbose: options.verbose,
                pricingSnapshot: options.pricingSnapshot,
                signal: options.signal,
                executors: options.executors,
                lintCommand: options.lintCommand,
            },
            exactSecrets: [options.github.token],
        },
        dependencies,
    );
    return writeLocalCycleResult(outputDir, result);
}
