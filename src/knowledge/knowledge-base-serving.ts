/**
 * Convert a Markdown heading into the fallback anchor generated by Docusaurus/GitHub.
 *
 * @param heading - Heading text without Markdown prefix.
 * @returns Lowercase dash-separated anchor.
 */
function normalizeHeadingAnchor(heading: string): string {
    return heading
        .trim()
        .toLowerCase()
        .replace(/[`*_]/gu, '')
        .replace(/[^\p{L}\p{N}\s-]/gu, '')
        .replace(/\s+/gu, '-');
}

/**
 * Extract one complete Markdown section through the next same-or-higher-level heading.
 *
 * @param content - Trusted allowlisted Markdown document.
 * @param section - Section identifier selected by the fixed topic map.
 * @returns Complete section excerpt.
 */
export function extractSection(content: string, section: GuidanceSection): string {
    const lines = content.split(/\r?\n/u);
    const explicitAnchor = `{#${section.anchor}}`;
    const startIndex = lines.findIndex((line) => {
        const match = /^(#{1,6})\s+(.+?)\s*$/u.exec(line);
        if (!match) {
            return false;
        }
        const headingText = match[2].replace(/\s*\{#[^}]+\}\s*$/u, '');
        return (
            line.includes(explicitAnchor) ||
            headingText.trim().toLowerCase() === section.heading.toLowerCase() ||
            normalizeHeadingAnchor(headingText) === section.anchor
        );
    });
    if (startIndex < 0) {
        throw new Error(
            `Pinned guidance section ${section.anchor} was not found in its allowlisted document.`,
        );
    }
    const headingMatch = /^(#{1,6})\s+/u.exec(lines[startIndex]);
    const headingLevel = headingMatch?.[1].length ?? 6;
    let endIndex = lines.length;
    for (let index = startIndex + 1; index < lines.length; index += 1) {
        const nextHeading = /^(#{1,6})\s+/u.exec(lines[index]);
        if (nextHeading && nextHeading[1].length <= headingLevel) {
            endIndex = index;
            break;
        }
    }
    return lines.slice(startIndex, endIndex).join('\n').trim();
}

/**
 * Resolve one trusted path and immutable citation for an allowlisted section.
 *
 * @param source - Prepared immutable document source.
 * @param section - Fixed section selected from the topic map.
 * @returns File content and citation metadata.
 */
export function resolveDocument(
    source: KnowledgeGuidanceSource,
    section: GuidanceSection,
): ResolvedGuidanceDocument {
    if (section.document === GuidanceDocumentRole.Contributing) {
        const filePath = 'CONTRIBUTING.md';
        return {
            content: readFileSync(source.contributingPath, 'utf8'),
            citation: {
                repository: source.filtersRepository,
                commit: source.filtersCommit,
                filePath,
                anchor: section.anchor,
                url:
                    `https://github.com/${source.filtersRepository}/blob/` +
                    `${source.filtersCommit}/${filePath}#${section.anchor}`,
            },
        };
    }
    const filePath =
        section.document === GuidanceDocumentRole.Syntax
            ? 'docs/general/ad-filtering/create-own-filters.md'
            : 'docs/general/ad-filtering/filter-policy.md';
    const localPath =
        section.document === GuidanceDocumentRole.Syntax ? source.syntaxPath : source.policyPath;
    return {
        content: readFileSync(localPath, 'utf8'),
        citation: {
            repository: source.knowledgeBaseRepository,
            commit: source.knowledgeBaseCommit,
            filePath,
            anchor: section.anchor,
            url:
                `https://github.com/${source.knowledgeBaseRepository}/blob/` +
                `${source.knowledgeBaseCommit}/${filePath}#${section.anchor}`,
        },
    };
}
