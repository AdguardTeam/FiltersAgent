/**
 * One allowlisted document section used to answer a guidance topic.
 */
export interface GuidanceSection {
    /**
     * Trusted source document selector.
     */
    document: GuidanceDocumentRole;

    /**
     * Stable Markdown anchor used to locate the section.
     */
    anchor: string;

    /**
     * Heading text fallback for documents that omit an explicit anchor.
     */
    heading: string;
}

/**
 * One trusted document loaded for a fixed guidance section.
 */
export interface ResolvedGuidanceDocument {
    /**
     * Complete allowlisted Markdown document content.
     */
    content: string;

    /**
     * Immutable citation for the selected section.
     */
    citation: KnowledgeGuidanceCitation;
}

